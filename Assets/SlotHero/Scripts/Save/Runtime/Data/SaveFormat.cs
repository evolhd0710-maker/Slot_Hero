namespace SlotHero.Save
{
    /// <summary>
    /// 저장 파일의 판 번호.
    ///
    /// **판 번호는 적기만 하고 읽는 데에는 쓰지 않는다.**
    /// 2026년 10월 8일 원재가 "버전 작성은 유지하되 그거에 영향을 받지 않게" 하라고 정했다.
    /// 업데이트를 해도 저장 형식이 늘 바뀌는 것은 아니고, 게임을 옛 판으로 되돌릴 일도 없다.
    /// 판 번호로 읽기를 막거나 올리는 단계를 두면 업데이트할 때 멀쩡한 저장이 버려질 수 있다.
    ///
    /// 예전에는 더 새 판이면 읽지 않았고, 더 옛 판이면 올리는 단계(`SaveMigration`)를 거쳤다.
    /// 올리는 단계가 없는 판이면 그 런을 버렸다. 둘 다 뺐다.
    ///
    /// 자료 구조를 고쳐도 대개는 손댈 것이 없다.
    /// `JsonUtility` 는 파일에 없는 칸을 기본값으로 두고, 모르는 칸은 버리고 읽는다.
    /// 체크섬도 파일에 적힌 글 그대로 확인하므로 칸이 늘거나 줄어도 걸리지 않는다(`SaveChecksum.VerifyJson`).
    ///
    /// **칸의 뜻을 바꿀 때만 조심한다.** 같은 이름에 다른 뜻을 담으면 옛 값이 새 뜻으로 읽힌다.
    /// 그때는 이름을 새로 짓는다. 설정의 연출 속도를 `effectSpeed` 에서 `presentationSpeed` 로 바꾼 것이 그 예다.
    /// 판 번호는 그런 일이 생겼을 때 어느 판으로 쓴 파일인지 알아보는 기록으로 남긴다.
    /// </summary>
    public static class SaveFormat
    {
        /// <summary>지금 판. 저장할 때 파일에 적는다. 자료 구조를 크게 고칠 때 올린다.</summary>
        public const int Current = 1;
    }
}
